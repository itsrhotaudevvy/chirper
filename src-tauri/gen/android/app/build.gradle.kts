// The Go core (go/out/<triple>/libchirpercore.so, built by scripts/build-go.sh) is copied into the
// jniLibs of each ABI before the native libraries are merged. An ABI whose library is missing is
// reported and left out; its APK then fails at runtime only on that ABI.
val chirperCoreAbis = mapOf(
    "aarch64-linux-android" to "arm64-v8a",
    "armv7-linux-androideabi" to "armeabi-v7a",
    "i686-linux-android" to "x86",
    "x86_64-linux-android" to "x86_64",
)
// Copies the Go core built by scripts/build-go.sh into jniLibs. A Copy task (not a doLast closure)
// so it is configuration-cache safe; ABIs whose library has not been built are simply skipped.
val chirperGoOut = rootProject.layout.projectDirectory.dir("../../../go/out")
val stageChirperCore by tasks.registering(Copy::class) {
    for ((triple, abi) in chirperCoreAbis) {
        from(chirperGoOut.file("$triple/libchirpercore.so")) { into(abi) }
    }
    into(layout.projectDirectory.dir("src/main/jniLibs"))
}
tasks.configureEach {
    if (name.startsWith("merge") && name.endsWith("JniLibFolders")) {
        dependsOn(stageChirperCore)
    }
}
